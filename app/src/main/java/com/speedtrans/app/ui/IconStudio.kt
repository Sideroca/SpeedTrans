    const val STYLE_RING = 1   // 双轨道环（交叉椭圆 + 环上珠 + 核心珠）

    /** 椭圆参数点：中心 cx,cy，轴 rx,ry，整体旋转 deg，取参数角 theta */
    private fun orbPoint(
        cx: Float, cy: Float, rx: Float, ry: Float, deg: Float, theta: Float
    ): Pair<Float, Float> {
        val rad = Math.toRadians(deg.toDouble())
        val cosD = cos(rad).toFloat()
        val sinD = sin(rad).toFloat()
        val t = Math.toRadians(theta.toDouble())
        val x0 = rx * cos(t).toFloat()
        val y0 = ry * sin(t).toFloat()
        return (cx + x0 * cosD - y0 * sinD) to (cy + x0 * sinD + y0 * cosD)
    }

    fun generate(styleId: Int, bg: Int, fg: Int, size: Int): Bitmap {
        val bmp = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
        val c = Canvas(bmp)
        c.drawColor(bg)
        val s = size.toFloat()
        val cx = s * 0.5f
        val cy = s * 0.52f
        val sw = s * 0.018f
        val p = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            style = Paint.Style.STROKE
            strokeWidth = sw
            color = fg
        }
        val dot = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = fg }
        fun dotAt(x: Float, y: Float, r: Float = s * 0.016f) = c.drawCircle(x, y, r, dot)

        if (styleId == STYLE_GRID) {
            // 网格轨道球（2026-09-11 定稿）：potrace 逐像素描摹的矢量路径（1:1，线条与珠一体）
            val op = buildOrbPath()
            op.fillType = Path.FillType.EVEN_ODD
            op.transform(Matrix().apply { setScale(s, s) })
            val fillP = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                color = fg
                style = Paint.Style.FILL
            }
            c.drawPath(op, fillP)
        } else {
            // 双轨道环（2026-09-10 定稿）：不再用参数拟合——直接把定稿图交给 potrace
            // 逐像素描摹成贝塞尔路径（1:1），线条与珠一体，绘制时整体 ×s。
            val rp = buildRingPath()
            rp.fillType = Path.FillType.EVEN_ODD   // potrace 路径含"孔洞"，y 翻转后 winding 反向，必须 EVEN_ODD
            rp.transform(Matrix().apply { setScale(s, s) })
            val fillP = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                color = fg
                style = Paint.Style.FILL
            }
            c.drawPath(rp, fillP)
        }
        return bmp
    }

